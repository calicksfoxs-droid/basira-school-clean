import { execFile } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

async function resolveCommit() {
  const envCommit = [
    process.env.GITHUB_SHA,
    process.env.GIT_COMMIT,
    process.env.CF_PAGES_COMMIT_SHA,
  ].find((value) => value && /^[0-9a-f]{40}$/iu.test(value.trim()));

  if (envCommit) return envCommit.trim().toLowerCase();

  try {
    const { stdout } = await execFileAsync("git", ["rev-parse", "HEAD"], {
      windowsHide: true,
    });
    const commit = stdout.trim();
    if (/^[0-9a-f]{40}$/iu.test(commit)) return commit.toLowerCase();
  } catch {
    // A source archive without .git metadata remains explicitly unverifiable.
  }

  return "local";
}

const commit = await resolveCommit();
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/build-info.ts",
  `// Generated by scripts/prepare-build-info.mjs. Do not edit.\nexport const BUILD_COMMIT: string = ${JSON.stringify(commit)};\n`,
  "utf8",
);
console.log(`Build commit stamp: ${commit}`);
